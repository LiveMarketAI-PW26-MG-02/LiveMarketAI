class DataValidator:
    """Validates generated synthetic data for quality and consistency."""

    @staticmethod
    def validate_ohlcv(df: pd.DataFrame) -> Tuple[bool, List[str]]:
        """Check OHLCV invariants: high >= close >= low, volume > 0, etc."""
        errors = []
        if "high" in df.columns and "low" in df.columns:
            if (df["high"] < df["low"]).any():
                errors.append("HIGH < LOW violations found")
            if "close" in df.columns:
                if (df["close"] > df["high"]).any():
                    errors.append("CLOSE > HIGH violations")
                if (df["close"] < df["low"]).any():
                    errors.append("CLOSE < LOW violations")
        if "volume" in df.columns:
            if (df["volume"] < 0).any():
                errors.append("Negative volume values found")
        if "close" in df.columns:
            if df["close"].isna().any():
                errors.append("NaN close prices found")
            if (df["close"] <= 0).any():
                errors.append("Non-positive close prices found")
        return len(errors) == 0, errors

    @staticmethod
    def validate_sentiment(df: pd.DataFrame) -> Tuple[bool, List[str]]:
        """Validate sentiment scores are in [-1, 1] range."""
        errors = []
        if "sentiment_score" in df.columns:
            if (df["sentiment_score"] > 1.0).any():
                errors.append("Sentiment > 1.0 found")
            if (df["sentiment_score"] < -1.0).any():
                errors.append("Sentiment < -1.0 found")
        if "follower_count" in df.columns:
            if (df["follower_count"] < 0).any():
                errors.append("Negative follower count")
        return len(errors) == 0, errors

    @staticmethod
    def validate_graph_data(graph_dict: dict) -> Tuple[bool, List[str]]:
        """Check graph data has required structure."""
        errors = []
        if "nodes" not in graph_dict:
            errors.append("Missing 'nodes' key")
        if "edges" not in graph_dict:
            errors.append("Missing 'edges' key")
        if graph_dict.get("nodes"):
            sample = graph_dict["nodes"][0]
            if "id" not in sample:
                errors.append("Node missing 'id' field")
        return len(errors) == 0, errors


