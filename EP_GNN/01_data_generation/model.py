class FeatureEngineeringEngine:
    """
    Computes EP-GNN-specific features from raw synthetic data.
    Features are designed to capture manipulation signatures specific
    to the Emotion Propagation Graph Neural Network approach.
    """

    FEATURE_GROUPS = {
        "price_based": [
            "log_return", "rolling_vol_5", "rolling_vol_20",
            "momentum_5", "momentum_20", "price_range_pct",
        ],
        "volume_based": [
            "volume_log", "volume_zscore", "vol_ma_ratio",
            "vwap_deviation", "volume_spike_flag",
        ],
        "microstructure": [
            "bid_ask_spread", "order_imbalance", "depth_total_log",
            "mid_price_move", "trade_intensity",
        ],
        "sentiment": [
            "avg_sentiment_1h", "sentiment_velocity", "sentiment_vol",
            "coordinated_post_ratio", "influencer_weighted_sentiment",
        ],
        "graph": [
            "degree_centrality", "betweenness_centrality",
            "clustering_coeff", "pagerank", "corr_neighborhood_avg",
        ],
    }

    def __init__(self):
        self.computed_features = {}

    def compute_price_features(self, df: pd.DataFrame) -> pd.DataFrame:
        """Compute price-based features."""
        df = df.copy()
        df["log_return"]      = np.log(df["close"] / df["close"].shift(1)).fillna(0)
        df["rolling_vol_5"]   = df["log_return"].rolling(5).std().fillna(0)
        df["rolling_vol_20"]  = df["log_return"].rolling(20).std().fillna(0)
        df["momentum_5"]      = df["close"].pct_change(5).fillna(0)
        df["momentum_20"]     = df["close"].pct_change(20).fillna(0)
        df["price_range_pct"] = ((df["high"] - df["low"]) / df["close"]).fillna(0)
        return df

    def compute_volume_features(self, df: pd.DataFrame) -> pd.DataFrame:
        """Compute volume-based anomaly features."""
        df = df.copy()
        df["volume_log"]    = np.log1p(df["volume"])
        vol_mean = df["volume"].rolling(20).mean().replace(0, 1)
        vol_std  = df["volume"].rolling(20).std().replace(0, 1)
        df["volume_zscore"] = ((df["volume"] - vol_mean) / vol_std).fillna(0)
        df["vol_ma_ratio"]  = (df["volume"] / vol_mean.replace(0, 1)).fillna(1)
        # VWAP deviation
        df["vwap"] = (df["close"] * df["volume"]).cumsum() / df["volume"].cumsum().replace(0, 1)
        df["vwap_deviation"]    = ((df["close"] - df["vwap"]) / df["vwap"].replace(0, 1)).fillna(0)
        df["volume_spike_flag"] = (df["volume_zscore"].abs() > 3.0).astype(int)
        return df

    def compute_sentiment_features(self, price_df: pd.DataFrame,
                                   sent_df: pd.DataFrame) -> pd.DataFrame:
        """Merge sentiment features into price dataframe."""
        sent_agg = sent_df.groupby("asset_id").agg(
            avg_sentiment_1h       = ("sentiment_score", "mean"),
            sentiment_vol          = ("sentiment_score", "std"),
            coordinated_post_ratio = ("is_coordinated", "mean"),
        ).reset_index()
        merged = price_df.merge(sent_agg, on="asset_id", how="left")
        merged["avg_sentiment_1h"].fillna(0, inplace=True)
        merged["sentiment_vol"].fillna(0, inplace=True)
        merged["coordinated_post_ratio"].fillna(0, inplace=True)
        merged["sentiment_velocity"] = merged.groupby("asset_id")["avg_sentiment_1h"].diff().fillna(0)
        return merged

    def compute_graph_features(self, G) -> dict:
        """Compute graph-theoretic features for each asset node."""
        import networkx as nx
        features = {}
        degree_centrality      = nx.degree_centrality(G)
        try:
            betweenness_centrality = nx.betweenness_centrality(G, normalized=True)
        except Exception:
            betweenness_centrality = {n: 0.0 for n in G.nodes()}
        try:
            clustering             = nx.clustering(G.to_undirected())
        except Exception:
            clustering             = {n: 0.0 for n in G.nodes()}
        try:
            pagerank               = nx.pagerank(G, alpha=0.85)
        except Exception:
            pagerank               = {n: 1.0/G.number_of_nodes() for n in G.nodes()}

        for node in G.nodes():
            features[node] = {
                "degree_centrality":     degree_centrality.get(node, 0),
                "betweenness_centrality": betweenness_centrality.get(node, 0),
                "clustering_coeff":      clustering.get(node, 0),
                "pagerank":              pagerank.get(node, 0),
            }
        return features

    def build_feature_matrix(self, price_df: pd.DataFrame,
                             sent_df: pd.DataFrame,
                             graph_features: dict) -> pd.DataFrame:
        """Assemble final feature matrix for GNN training."""
        enriched = self.compute_price_features(price_df)
        enriched = self.compute_volume_features(enriched)
        enriched = self.compute_sentiment_features(enriched, sent_df)

        # Add graph features per asset
        for feat_name in ["degree_centrality", "betweenness_centrality",
                          "clustering_coeff", "pagerank"]:
            enriched[feat_name] = enriched["asset_id"].map(
                {k: v.get(feat_name, 0) for k, v in graph_features.items()}
            ).fillna(0)

        feature_cols = (
            ["log_return", "rolling_vol_5", "rolling_vol_20",
             "momentum_5", "momentum_20", "price_range_pct",
             "volume_log", "volume_zscore", "vol_ma_ratio",
             "vwap_deviation", "volume_spike_flag",
             "avg_sentiment_1h", "sentiment_vol",
             "coordinated_post_ratio", "sentiment_velocity",
             "degree_centrality", "betweenness_centrality",
             "clustering_coeff", "pagerank"]
        )
        existing_cols = [c for c in feature_cols if c in enriched.columns]
        return enriched[["asset_id", "timestamp", "is_manipulation"] + existing_cols]


