class DatasetManifestBuilder:
    """Builds a manifest describing the generated dataset for reproducibility."""

    def __init__(self, module_name: str = "EP-GNN"):
        self.manifest = {
            "module": module_name,
            "full_name": "Emotion Propagation Graph Neural Network",
            "generated_at": datetime.utcnow().isoformat() + "Z",
            "random_seed": 42,
            "files": [],
            "statistics": {},
            "data_hash": None,
        }

    def register_file(self, filepath: str, n_rows: int, description: str) -> None:
        self.manifest["files"].append({
            "path": filepath,
            "n_rows": n_rows,
            "description": description,
            "checksum": self._checksum(filepath),
        })

    def _checksum(self, filepath: str) -> Optional[str]:
        if not os.path.exists(filepath):
            return None
        h = hashlib.md5()
        with open(filepath, "rb") as f:
            for chunk in iter(lambda: f.read(8192), b""):
                h.update(chunk)
        return h.hexdigest()

    def add_statistics(self, key: str, value: Any) -> None:
        self.manifest["statistics"][key] = value

    def save(self, output_path: str = "outputs/ep_gnn_data/manifest.json") -> None:
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        with open(output_path, "w") as f:
            json.dump(self.manifest, f, indent=2, default=str)
        print(f"  Manifest saved → {output_path}")


